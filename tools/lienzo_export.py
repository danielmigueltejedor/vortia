#!/usr/bin/env python3
"""Export the Lienzo design tokens for non-Qt apps.

Usage: lienzo_export.py [--check]

Reads resources/lienzo/tokens.json and writes resources/lienzo/lienzo.css:
CSS custom properties for the light scheme, the dark scheme under
`prefers-color-scheme: dark`, and explicit `[data-theme]` overrides.
With --check, fails if the committed file is out of date.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "resources" / "lienzo"


def kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


def colour_block(colours: dict, indent: str) -> str:
    return "".join(f"{indent}--lienzo-color-{kebab(k)}: {v};\n" for k, v in colours.items())


def render(tokens: dict) -> str:
    light, dark = tokens["color"]["light"], tokens["color"]["dark"]
    out = [f"/* {tokens['name']} · {tokens['variant']} {tokens['version']} — generated by tools/lienzo_export.py"
           " from tokens.json. Do not edit. */\n", ":root {\n", colour_block(light, "  ")]
    for group in ("radius", "space", "size", "font", "border"):
        for key, value in tokens[group].items():
            out.append(f"  --lienzo-{group}-{kebab(key)}: {value}px;\n")
    out.append("}\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n")
    out.append(colour_block(dark, "    "))
    out.append("  }\n}\n:root[data-theme=\"dark\"] {\n")
    out.append(colour_block(dark, "  "))
    out.append("}\n")
    return "".join(out)


def main() -> int:
    tokens = json.loads((ROOT / "tokens.json").read_text(encoding="utf-8"))
    css = render(tokens)
    target = ROOT / "lienzo.css"
    if "--check" in sys.argv[1:]:
        if not target.exists() or target.read_text(encoding="utf-8") != css:
            print("resources/lienzo/lienzo.css is out of date: run tools/lienzo_export.py", file=sys.stderr)
            return 1
        return 0
    target.write_text(css, encoding="utf-8")
    print(f"Wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
