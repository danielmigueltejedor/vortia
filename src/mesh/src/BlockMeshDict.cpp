namespace vortia {

std::string_view toString(PatchKind kind) {
    switch (kind) {
    case PatchKind::Wall: return "wall";
    case PatchKind::Patch: return "patch";
    case PatchKind::Empty: return "empty";
    case PatchKind::Symmetry: return "symmetry";
    }
    return "patch";
}

namespace {

/// Formats a double the way OpenFOAM dictionaries expect: compact, with
/// enough digits to round-trip (and never locale-dependent).
std::string fmt(double value) {
    if (value == 0.0)
        return "0";
    std::ostringstream out;
    out << std::setprecision(10) << std::defaultfloat << value;
    return out.str();
}

std::string fmtVec(const Vec3& v) {
    return "(" + fmt(v.x) + " " + fmt(v.y) + " " + fmt(v.z) + ")";
}

[[nodiscard]] bool isValidPatchName(const std::string& name) {
    if (name.empty() || std::isdigit(static_cast<unsigned char>(name.front())))
        return false;
    return std::all_of(name.begin(), name.end(), [](char c) {
        return std::isalnum(static_cast<unsigned char>(c)) || c == '_' || c == '-';
    });
}

Expected<void> validate(const BlockMeshParams& params) {
    for (int i = 0; i < 3; ++i) {
        if (params.cells[i] < 1)
            return Error::make(ErrorCode::InvalidArgument,
                               "blockMesh cells must be >= 1 in every direction");
        if (!std::isfinite(params.grading[i]) || params.grading[i] <= 0.0)
            return Error::make(ErrorCode::InvalidArgument,
                               "blockMesh grading must be finite and positive");
    }
    if (!std::isfinite(params.convertToMeters) || params.convertToMeters <= 0.0)
        return Error::make(ErrorCode::InvalidArgument, "convertToMeters must be positive");

    std::set<std::string> names;
    std::array<bool, 6> seenFaces{};
    for (const auto& patch : params.patches) {
        const int f = static_cast<int>(patch.face);
        if (f < 0 || f > 5)
            return Error::make(ErrorCode::InvalidArgument, "patch face index out of range");
        if (seenFaces[f])
            return Error::make(ErrorCode::InvalidArgument,
                               "duplicate patch for face " + std::to_string(f));
        seenFaces[f] = true;
        if (!isValidPatchName(patch.name))
            return Error::make(ErrorCode::InvalidArgument,
                               "invalid OpenFOAM patch name '" + patch.name + "'");
        if (!names.insert(patch.name).second)
            return Error::make(ErrorCode::InvalidArgument,
                               "duplicate patch name '" + patch.name + "'");
    }
    for (int f = 0; f < 6; ++f)
        if (!seenFaces[f])
            return Error::make(ErrorCode::InvalidArgument,
                               "missing patch for face " + std::to_string(f));
    return {};
}

} // namespace

Expected<std::string> BlockMeshDict::generate(const BoxDomain& domain,
                                              const BlockMeshParams& params) {
    if (auto ok = validate(params); !ok)
        return ok.error();

    const auto vertices = domain.blockVertices();
    const auto faces = BoxDomain::faceVertices();

    std::ostringstream out;
    out << "/*--------------------------------*- C++ -*----------------------------------*\\\n"
        << "| Generated by Vortia — do not edit by hand; regenerate from the project.   |\n"
        << "\\*---------------------------------------------------------------------------*/\n"
        << "FoamFile\n{\n"
        << "    version     2.0;\n"
        << "    format      ascii;\n"
        << "    class       dictionary;\n"
        << "    object      blockMeshDict;\n"
        << "}\n"
        << "// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //\n\n"
        << "convertToMeters " << fmt(params.convertToMeters) << ";\n\n"
        << "vertices\n(\n";
    for (const auto& v : vertices)
        out << "    " << fmtVec(v) << "\n";
    out << ");\n\n"
        << "blocks\n(\n"
        << "    hex (0 1 2 3 4 5 6 7) (" << params.cells[0] << " " << params.cells[1] << " "
        << params.cells[2] << ") simpleGrading (" << fmt(params.grading[0]) << " "
        << fmt(params.grading[1]) << " " << fmt(params.grading[2]) << ")\n"
        << ");\n\n"
        << "boundary\n(\n";
    for (const auto& patch : params.patches) {
        const auto& quad = faces[static_cast<std::size_t>(patch.face)];
        out << "    " << patch.name << "\n    {\n"
            << "        type " << toString(patch.kind) << ";\n"
            << "        faces\n        (\n"
            << "            (" << quad[0] << " " << quad[1] << " " << quad[2] << " " << quad[3]
            << ")\n"
            << "        );\n    }\n";
    }
    out << ");\n\n"
        << "// ************************************************************************* //\n";

    log(LogLevel::Debug, "Generated blockMeshDict for box domain");
    return out.str();
}

} // namespace vortia
